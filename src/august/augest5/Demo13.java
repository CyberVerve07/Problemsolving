package august.augest5;

public class Demo13 {
    public static void main(String[] args) {
        // Loop from 'a' to 'z' to print lowercase letters
        for (char c = 'a'; c <= 'z'; c++) {
            System.out.print(c + " ");
        }

        System.out.println(); // Move to a new line

        // Loop from 'A' to 'Z' to print uppercase letters
        for (char c = 'A'; c <= 'Z'; c++) {
            System.out.print(c + " ");
        }
    }


}

